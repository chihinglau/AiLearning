POOLS = dict(ALL_KINDS)


def make_item(kind_name: str, entry) -> tuple[str, str, str]:
    """把池中词条渲染成 (题干, 答案, 解析)。"""
    if kind_name == "liangci":
        noun, measure = entry
        return (f"在括号里填上合适的量词：一（　）{noun}。", measure,
                f"「{noun}」的常用量词是「{measure}」。")
    if kind_name == "fanyi":
        word, opp = entry
        return (f"写出「{word}」的反义词：________。", opp,
                f"「{word}」与「{opp}」意思相反。")
    if kind_name == "jinyi":
        word, syn = entry
        return (f"写出「{word}」的近义词：________。", syn,
                f"「{word}」与「{syn}」意思相近。")
    if kind_name == "chengyu":
        broken, missing = entry
        return (f"把成语补充完整：{broken}。", missing,
                f"该成语完整形式缺字为「{missing}」。")
    if kind_name == "gushi":
        first, second, source = entry
        return (f"补写诗句：「{first}，________。」", second, f"出自{source}。")
    if kind_name == "biaodian":
        sentence, mark = entry
        kind_cn = {"。": "陈述", "？": "疑问", "！": "感叹"}[mark]
        return (f"给句子加上合适的句末标点：「{sentence}（　）」", mark,
                f"该句为{kind_cn}句，句末用「{mark}」。")
    pattern, conj = entry
    return (f"填上合适的关联词：{pattern}", conj, f"此处应填关联词「{conj}」。")


def build_items_for_chapter(allowed: set[str] | None = None,
                            per_chapter: int = 4,
                            counters: dict[str, int] | None = None):
    """生成某章节的填空条目。

    `counters` 由调用方**跨册持有**（全局游标），保证全库同词条均匀摊开而非每册重置。
    """
    kinds = [(k, POOLS[k]) for k, _ in ALL_KINDS if not allowed or k in allowed]
    if not kinds:
        kinds = [("jinyi", JINYI)]
    counters = counters if counters is not None else {}
    for kind_name, pool in kinds:
        counters.setdefault(kind_name, 0)
    out = []
    for i in range(per_chapter):
        kind_name, pool = kinds[i % len(kinds)]
        pos = counters[kind_name] % len(pool)
        counters[kind_name] = pos + 1
        out.append(make_item(kind_name, pool[pos]) + (kind_name,))
    return out


__all__ = ["build_items_for_chapter", "POOLS"]
