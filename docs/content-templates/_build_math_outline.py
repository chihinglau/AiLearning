def units_from_raw(items):
    """把电子课本网目录序列折成 [(容器名, [子项])]；「第X章 → 1 ...」两级结构。"""
    rows = []
    cur_unit = None
    cur_unit_children = []
    chap = None

    def flush_chap():
        nonlocal chap
        if chap is not None:
            rows.append(chap)
            chap = None

    def flush_unit():
        nonlocal cur_unit, cur_unit_children
        flush_chap()
        if cur_unit is not None:
            rows.append((cur_unit, cur_unit_children))
        cur_unit, cur_unit_children = None, []

    for it in items:
        if it.startswith("第") and "单元" in it:
            flush_unit()
            cur_unit = it
        elif it.startswith("第") and "章" in it:
            flush_unit()
            cur_unit = it
        elif it in ("回顾与思考", "复习题", "手机版", "电子课本网"):
            continue
        else:
            if cur_unit is None:
                cur_unit = "（开篇）"
            cur_unit_children.append(it)
    flush_unit()
    return rows


def with_alias(name: str) -> str:
    """单元/章名同时收录「带序号」与「裸名」两种写法，避免每日文件写裸名时误判越界。"""
    m = re.match(r"^(第[一二三四五六七八九十]+(?:单元|章))\s*(.+)$", name)
    if m:
        return f"{name} / {m.group(2)}"
    return name


