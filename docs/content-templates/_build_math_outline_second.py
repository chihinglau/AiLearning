def units_from_raw(items):
    rows = []
    cur_unit = None
    cur_unit_children = []
    chap = None

    def flush_chap():
        nonlocal chap
        if chap is not None:
            rows.append(chap)
            chap = None

    def flush_unit():
        nonlocal cur_unit, cur_unit_children
        flush_chap()
        if cur_unit is not None:
            rows.append((cur_unit, cur_unit_children))
        cur_unit, cur_unit_children = None, []

    for it in items:
        if it in ("手机版", "电子课本网", "回顾与思考", "复习题"):
            continue
        if it.startswith("第") and ("单元" in it or "章" in it):
            flush_unit()
            cur_unit = it
        else:
            if cur_unit is None:
                cur_unit = "（开篇）"
            cur_unit_children.append(it)
    flush_unit()
    return rows


def with_alias(name: str) -> str:
    m = re.match(r"^(第[一二三四五六七八九十]+(?:单元|章))\s*(.+)$", name)
    if m:
        return f"{name} / {m.group(2)}"
    return name


