# 生成题目模板：每个点 5 题（2/2/3/3/4 难度按题型固定）
def build_chapter(n):
    ch = PACK["chapters"]
    u_title, u_sum = UNITS[n - 1]
    points = []
    for pt in DATA[n]:
        items = pt["items"]
        w1, m1 = items[0]
        w2, m2 = items[1]
        w3, m3 = items[2]
        w4, m4 = items[3]
        pname = pt["name"]
        qs = [
            ("choice", "「%s」的意思是（ ）。" % m1, [w1, w2, w3, w4], "A", "「%s」的意思是%s，与选项 A 对应。" % (w1, m1), 2),
            ("fill", "根据中文写英文：%s（ ）。" % m2, None, w2, "「%s」的英文是 %s。" % (m2, w2), 2),
            ("judge", "「%s」表示「%s」。这一说法是正确的。" % (w3, m3), None, "T", "「%s」的意思确实是%s。" % (w3, m3), 3),
            ("multiple", "与本单元相关的表达中，表示「%s」和「%s」的有（ ）。" % (m1, m3), [w1, w2, w3, w4], ["A", "C"], "A ✓ 对应%s；B ✗ 对应%s；C ✓ 对应%s；D ✗ 对应%s。所以选 A、C。" % (m1, m2, m3, m4), 3),
            ("answer", "用「%s」写一句英文，并写出中文意思。" % w1, None, "示例：I %s every day. 我每天%s。" % (w1, m1), "评分要点：用上目标表达 + 句子通顺 + 中文准确。", 4),
        ]
        points.append({"name": pname, "explanation": "本知识点为%s，要求能认读并在句子中正确使用。" % pt["note"], "questions": qs})
    ch.append({"name": u_title, "summary": u_sum, "points": points})


for i in range(1, 10):
    build_chapter(i)
